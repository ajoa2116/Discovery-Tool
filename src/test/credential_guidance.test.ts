const first=(vendor:string,model='',firmware='')=>guidance(vendor,model,firmware)[0];
check(first('Hanwha Vision','QND-7082R').id==='hanwha-qnd7082r','exact model outranks manufacturer');
check(guidance('Hanwha Vision','QND-7082R').length===1,'strong model suppresses weaker suggestions');
check(first('Unknown','QND-7082R').passwordState==='INITIAL_SETUP','partial identity preserves model first-login evidence');
check(!first('Unknown','QND-7082R').passwordValue,'QND password is never invented');
check(first('Samsung Techwin',' wisenet QND–7082R ').id==='hanwha-qnd7082r','lineage and model normalization');
check(first('AXIS Communications',' axis 2120 ').id==='axis-2120-legacy','Axis prefix and whitespace normalization');
check(first('Hikvision','','V5.2.0 build 140721').confidence==='FAMILY','documented firmware generation outranks manufacturer');
check(guidance('Hikvision','','5.1.9').length===1,'family suppresses contradictory activation fallback');
check(first('Hikvision','','5.2.1').passwordState==='INITIAL_SETUP','later firmware does not inherit historical password');
check(first('Hikvision','','unknown').confidence==='MANUFACTURER','absent family evidence uses manufacturer guidance');
check(first('Dahua Technology').passwordState==='INITIAL_SETUP','Dahua initialization guidance');
check(first('UNV').passwordState==='UNKNOWN'&&!first('UNV').passwordValue,'Uniview username only');
check(!first('UNV').source.url&&!!first('UNV').source.title,'missing verified URL keeps textual provenance');
check(first('Axis','P3265').passwordState==='INITIAL_SETUP','new Axis model never inherits legacy model password');
check(guidance('Hikvision','2120').length===0,'conflicting manufacturer suppresses exact-model credential');
check(guidance('Unsupported vendor').length===0,'unsupported known manufacturer does not receive generic guesses');
