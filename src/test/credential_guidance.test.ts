check(generic.length===2,'generic historical list remains bounded');
check(new Set(generic.map(x=>x.id)).size===2,'multiple historical suggestions independently identified');
check(generic.every(x=>x.scope==='Generic legacy camera'&&x.confidence==='LOW'),'generic applicability always explicit');
check(generic.every(x=>x.notes.includes('not evidence about this camera')),'generic entries do not infer camera vendor');
check(factoryCredentialHint('Unknown','Unknown')===null,'compatibility accessor does not turn generic into device evidence');
check(FACTORY_CREDENTIAL_HINTS.every(x=>!!x.source.title&&!!x.source.reviewed),'every catalog entry retains provenance');
check(first('Axis','2120').source.url?.startsWith('https://www.axis.com/'),'existing official manual link preserved');
check(FACTORY_CREDENTIAL_HINTS.filter(x=>x.passwordState!=='VALUE').every(x=>!x.passwordValue),'non-value states carry no password');
const before=JSON.stringify(FACTORY_CREDENTIAL_HINTS);guidance('Unknown');
check(JSON.stringify(FACTORY_CREDENTIAL_HINTS)===before,'generic lookup never rewrites catalog evidence');
