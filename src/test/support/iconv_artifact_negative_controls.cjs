// Inert record mutations shared by archival checks and the fresh-build fixture.
const assert=require('node:assert/strict');
const {buildPackageAdmission}=require('../../../scripts/staged-backend-review.cjs');
const {facade}=require('./iconv_artifact_metadata.cjs');
const clone=v=>JSON.parse(JSON.stringify(v));
const denied=(run,reason)=>assert.throws(run,e=>e.code==='GENERATED_ARTIFACT_DENIED'&&(!reason||e.reason===reason));
function isolatedMutation(f,issue,mutate,reason){
  const previous=f.manifest,previousSelection=f.selection,unchanged=clone(previous);
  const restore=mutate();issue();
  assert.notEqual(f.manifest,previous);assert.notEqual(f.selection,previousSelection);
  assert.deepEqual(previous,unchanged,'A new case must not alter an earlier manifest');
  const owner=f.session();denied(()=>owner.admit(),reason);assert.equal(owner.denied,true);
  restore(); // Restoring the fixture model cannot revive the already denied owner.
  denied(()=>owner.admit(),'sticky-denial');
  denied(()=>f.session(),'selection-owner');
  delete f.manifest.generatedArtifact;
  const candidate=f.manifest.candidates.find(c=>c.output===facade);
  candidate.source=candidate.output;candidate.status='copied-candidate';
  denied(()=>buildPackageAdmission(f.manifest,[{path:facade,reason:'Historical copied source pathname.'}]));
  denied(()=>buildPackageAdmission(f.manifest,f.content.sources.map(s=>({path:s.path,reason:'Source-only review cannot admit generated bytes.'}))));
  denied(()=>owner.admit(),'sticky-denial');
  assert.deepEqual(previous,unchanged);
  return reason;
}
function missingSourceEdge(f,issue=()=>f.refresh()){
  assert.equal(f.content.sourceEdges.length,38);
  return isolatedMutation(f,issue,()=>{
    const removed=f.content.sourceEdges.pop();assert.ok(Number.isInteger(removed.occurrence));
    assert.equal(f.content.sourceEdges.length,37);
    return ()=>f.content.sourceEdges.push(removed);
  },'iconv-normalized-edges');
}
function incorrectCompilerOptions(f,issue=()=>f.refresh()){
  assert.equal(f.content.derivation.options.target,'node24');
  return isolatedMutation(f,issue,()=>{
    f.content.derivation.options.target='node22';
    return ()=>{f.content.derivation.options.target='node24';};
  },'iconv-compiler-options');
}
module.exports={missingSourceEdge,incorrectCompilerOptions};
